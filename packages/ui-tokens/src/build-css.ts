/**
 * Generates CSS variables from the tokens (section 6.3). The stylesheet in
 * apps/web/src/styles/tokens.css is generated; editing it by hand is a bug.
 */
import { tokens } from './tokens';

const PREFIX = '--rp';

function kebab(value: string): string {
  return value.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`);
}

function flatten(group: string, obj: Record<string, string | number>): string[] {
  return Object.entries(obj).map(
    ([key, value]) => `  ${PREFIX}-${kebab(group)}-${kebab(key)}: ${value};`,
  );
}

export function cssVariables(): string {
  const lines = [
    '/* Generated by packages/ui-tokens/build-css.ts. Do not edit by hand. */',
    ':root {',
    ...flatten('color', tokens.color),
    ...flatten('map', tokens.map),
    ...flatten('delay', tokens.delayColor),
    ...flatten('delay-tint', tokens.delayTint),
    ...flatten('space', tokens.space),
    ...flatten('radius', tokens.radius),
    ...flatten('shadow', tokens.shadow),
    ...flatten('font', tokens.font),
    ...flatten('layout', tokens.layout),
    `  ${PREFIX}-touch-target: ${tokens.touchTarget};`,
    '}',
    '',
  ];
  return lines.join('\n');
}

/** Same data as a TypeScript object for code that needs a value at runtime. */
export function cssVar(name: keyof typeof tokens.color | string): string {
  return `var(${PREFIX}-${name})`;
}
